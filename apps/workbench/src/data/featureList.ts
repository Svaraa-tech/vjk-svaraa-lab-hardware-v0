/** All Svaraas a feature is associated with (primary + also). */
export function featureSvaraas(f: FeatureItem): SvaraaPillar[] {
  const set = new Set<SvaraaPillar>([f.pillar, ...(f.alsoSvaraas ?? [])]);
  return SVARAA_SORT.filter((p) => set.has(p));
}

export function featureActors(f: FeatureItem): CareActor[] {
  return f.actors?.length ? f.actors : ["wearer"];
}

