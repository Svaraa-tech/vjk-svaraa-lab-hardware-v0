/** Product feature backlog for Svaraa elder-care — mapped to V0 Lab hardware. */

export type SvaraaPillar =
  | "Recite"
  | "Respond"
  | "Remind"
  | "Rescue"
  | "Recall"
  | "Repository"
  | "Riddle"
  | "Platform";

export type FeatureMaturity =
  | "v0_bench"
  | "product_path"
  | "needs_phone"
  | "needs_cloud"
  | "later_gated";

/** Product priority for roadmap ordering within each Svaraa. */
export type FeaturePriority = "P1" | "P2" | "P3";

/** Who the feature serves in a many-to-many care graph. */
export type CareActor =
  | "wearer"
  | "guardian"
  | "care_circle"
  | "both_ends";

export type FeatureSub = {
  id: string;
  name: string;
  summary: string;
  actors?: CareActor[];
};

export type FeatureItem = {
  id: string;
  /** Primary Svaraa this feature ships under (card grouping). */
  pillar: SvaraaPillar;
  /** Extra Svaraas this feature also touches (cross-links). */
  alsoSvaraas?: SvaraaPillar[];
  name: string;
  summary: string;
  elderWhy: string;
  how: string;
  hardware: string[];
  maturity: FeatureMaturity;
  /** P1 Must have · P2 Need to have · P3 Good to have */
  priority: FeaturePriority;
  /**
   * Custom PCB / Svaraa Pendant microcontroller + production parts mapping.
   * Sourced from Svaraa_Feature_Priority_Hardware.xlsx (see mcuEquivalents.ts).
   */
  mcuEquivalent?: string;
  /** Many-to-many: who acts / who receives. Defaults to wearer if omitted. */
  actors?: CareActor[];
  subFeatures?: FeatureSub[];
  tags?: string[];
};

